def _admit_frozen_evaluation(root: Path, analysis_root: Path, run_manifest: dict,
                             freeze: dict, environment_report_path: Path) -> dict:
    """Fail before V0 errors if the captured version or immutable inputs drift."""
    if _read_json(analysis_root / "analysis_run_manifest.json") != run_manifest:
        raise RuntimeError("analysis run manifest changed before V0 evaluation")
    if _read_json(analysis_root / "analysis_freeze.json") != freeze:
        raise RuntimeError("analysis freeze changed before V0 evaluation")
    for name in ("algorithm_sha256", "dependencies", "source_protocol",
                 "bundled_legacy_protocol_sha256", "mc_trial_count", "pixel_sigma_px", "huber_f_scale"):
        if freeze.get(name) != run_manifest.get(name):
            raise RuntimeError(f"{name} identity changed before V0 evaluation")
    if (_analysis_hashes() != run_manifest["algorithm_sha256"]
            or _analysis_dependencies() != run_manifest["dependencies"]):
        raise RuntimeError("current algorithm/dependency identity changed before V0 evaluation")
    if _sha256(environment_report_path) != run_manifest["environment_report_sha256"]:
        raise RuntimeError("environment report changed before V0 evaluation")
    for name, expected in run_manifest["source_campaign_manifest_sha256"].items():
        if _sha256(root / name) != expected:
            raise RuntimeError(f"source manifest changed before V0 evaluation: {name}")
    for filename, field in (
        ("path_selection.json", "path_selection_sha256"),
        ("calibration_freeze_manifest.json", "primary_calibration_checksums_manifest_sha256"),
        ("sensitivity_calibration_manifest.json", "sensitivity_calibration_manifest_sha256"),
        ("sensitivity_calibration_checksums.json", "sensitivity_calibration_checksums_sha256"),
    ):
        if _sha256(analysis_root / filename) != freeze[field]:
            raise RuntimeError(f"frozen calibration/selection artifact changed before V0 evaluation: {filename}")
    # Reuse source-aware full raw QC, not just markers or checksum-list hashes.
    current_status, current_slots = _status_slots(root)
    _, current_protocol = _load_analysis_protocol(root, current_status)
    if current_protocol != run_manifest["source_protocol"]:
        raise RuntimeError("source protocol identity changed before V0 evaluation")
    current_attempts = {}
    for slot in current_slots:
        attempt = slot["attempts"][-1]
        checksum = root / attempt["recording_path"] / "checksums.sha256"
        if checksum.is_file():
            current_attempts[f"{slot['run_id']}/{attempt['attempt_id']}"] = _sha256(checksum)
    if current_attempts != run_manifest["source_attempt_checksums_sha256"]:
        raise RuntimeError("source attempts changed before V0 evaluation")
    admission = {
        "status": "PRE_V0_IDENTITY_CHECK_PASSED",
        "stage": "before any V0 positioning-error evaluation",
        "analysis_freeze_sha256": _sha256(analysis_root / "analysis_freeze.json"),
        "analysis_run_manifest_sha256": _sha256(analysis_root / "analysis_run_manifest.json"),
        "source_identity_sha256": run_manifest["source_identity_sha256"],
        "algorithm_sha256": run_manifest["algorithm_sha256"],
        "source_protocol": run_manifest["source_protocol"],
        "raw_valid_run_count": current_status["valid_run_count"],
    }
    _write_immutable(analysis_root / "evaluation_admission.json", admission)
    return admission


def _quaternion_matrix_xyzw(values: Iterable[float]) -> np.ndarray:
    x, y, z, w = (float(value) for value in values)
    norm = math.sqrt(x * x + y * y + z * z + w * w)
    if not math.isfinite(norm) or norm < 1e-12:
        raise ValueError("camera truth quaternion must be finite and nonzero")
    x, y, z, w = x / norm, y / norm, z / norm, w / norm
    return np.array([
        [1 - 2 * (y * y + z * z), 2 * (x * y - z * w), 2 * (x * z + y * w)],
        [2 * (x * y + z * w), 1 - 2 * (x * x + z * z), 2 * (y * z - x * w)],
        [2 * (x * z - y * w), 2 * (y * z + x * w), 1 - 2 * (x * x + y * y)],
    ])


